-- Base local del Automatizador de Reportes (H2 en ~/.automatizador-reportes/)

CREATE TABLE plantilla (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(200)  NOT NULL,
    tipo            VARCHAR(10)   NOT NULL,
    ruta            VARCHAR(1000) NOT NULL,
    marcadores      VARCHAR(4000),
    columnas_tabla  VARCHAR(4000),
    tiene_tabla     BOOLEAN       NOT NULL DEFAULT FALSE,
    descripcion     VARCHAR(1000),
    integrada       BOOLEAN       NOT NULL DEFAULT FALSE,
    creada          TIMESTAMP     NOT NULL
);

CREATE TABLE perfil_mapeo (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(200)  NOT NULL,
    plantilla_id    BIGINT        NOT NULL REFERENCES plantilla (id) ON DELETE CASCADE,
    mapeo           VARCHAR(8000),
    modo            VARCHAR(20)   NOT NULL,
    columna_nombre  VARCHAR(200),
    creado          TIMESTAMP     NOT NULL,
    ultimo_uso      TIMESTAMP
);

CREATE TABLE ejecucion (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha               TIMESTAMP     NOT NULL,
    plantilla_nombre    VARCHAR(200)  NOT NULL,
    archivo_datos       VARCHAR(1000) NOT NULL,
    modo                VARCHAR(20)   NOT NULL,
    formato             VARCHAR(10)   NOT NULL,
    carpeta_salida      VARCHAR(1000) NOT NULL,
    filas_procesadas    INT           NOT NULL,
    informes_generados  INT           NOT NULL,
    estado              VARCHAR(20)   NOT NULL,
    mensajes            VARCHAR(8000),
    duracion_ms         BIGINT        NOT NULL
);

CREATE TABLE ajuste (
    clave   VARCHAR(100)  PRIMARY KEY,
    valor   VARCHAR(2000)
);
