-- StockFlow local database (H2 in ~/.stockflow/)

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)  NOT NULL UNIQUE,
    description VARCHAR(500)
);

CREATE TABLE suppliers (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tax_id       VARCHAR(30),
    name         VARCHAR(200)  NOT NULL,
    contact_name VARCHAR(200),
    phone        VARCHAR(50),
    email        VARCHAR(200),
    address      VARCHAR(300),
    active       BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP     NOT NULL
);

CREATE TABLE products (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku            VARCHAR(50)    NOT NULL UNIQUE,
    name           VARCHAR(200)   NOT NULL,
    description    VARCHAR(1000),
    category_id    BIGINT         REFERENCES categories (id) ON DELETE SET NULL,
    supplier_id    BIGINT         REFERENCES suppliers (id) ON DELETE SET NULL,
    cost_price     DECIMAL(14, 2) NOT NULL DEFAULT 0,
    sale_price     DECIMAL(14, 2) NOT NULL DEFAULT 0,
    stock          INT            NOT NULL DEFAULT 0,
    min_stock      INT            NOT NULL DEFAULT 0,
    unit           VARCHAR(20)    NOT NULL DEFAULT 'UND',
    active         BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP      NOT NULL,
    updated_at     TIMESTAMP      NOT NULL,
    CONSTRAINT ck_products_stock CHECK (stock >= 0)
);

CREATE TABLE customers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_type   VARCHAR(10)   NOT NULL DEFAULT 'CC',
    document_number VARCHAR(30)   NOT NULL UNIQUE,
    name            VARCHAR(200)  NOT NULL,
    phone           VARCHAR(50),
    email           VARCHAR(200),
    address         VARCHAR(300),
    created_at      TIMESTAMP     NOT NULL
);

CREATE TABLE invoices (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number          VARCHAR(30)    NOT NULL UNIQUE,
    customer_id     BIGINT         REFERENCES customers (id),
    issued_at       TIMESTAMP      NOT NULL,
    subtotal        DECIMAL(14, 2) NOT NULL,
    discount        DECIMAL(14, 2) NOT NULL DEFAULT 0,
    tax_rate        DECIMAL(5, 2)  NOT NULL,
    tax             DECIMAL(14, 2) NOT NULL,
    total           DECIMAL(14, 2) NOT NULL,
    payment_method  VARCHAR(20)    NOT NULL,
    amount_paid     DECIMAL(14, 2) NOT NULL DEFAULT 0,
    status          VARCHAR(20)    NOT NULL,
    notes           VARCHAR(1000),
    cancelled_at    TIMESTAMP
);

CREATE TABLE invoice_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id   BIGINT         NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
    product_id   BIGINT         NOT NULL REFERENCES products (id),
    product_sku  VARCHAR(50)    NOT NULL,
    product_name VARCHAR(200)   NOT NULL,
    quantity     INT            NOT NULL,
    unit_price   DECIMAL(14, 2) NOT NULL,
    unit_cost    DECIMAL(14, 2) NOT NULL,
    line_total   DECIMAL(14, 2) NOT NULL,
    CONSTRAINT ck_invoice_items_quantity CHECK (quantity > 0)
);

CREATE TABLE stock_movements (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     BIGINT        NOT NULL REFERENCES products (id),
    movement_type  VARCHAR(30)   NOT NULL,
    quantity       INT           NOT NULL,
    stock_after    INT           NOT NULL,
    unit_cost      DECIMAL(14, 2),
    reference      VARCHAR(100),
    notes          VARCHAR(500),
    created_at     TIMESTAMP     NOT NULL
);

CREATE TABLE settings (
    setting_key   VARCHAR(100)  PRIMARY KEY,
    setting_value VARCHAR(2000)
);

CREATE INDEX ix_products_name ON products (name);
CREATE INDEX ix_invoices_issued_at ON invoices (issued_at);
CREATE INDEX ix_invoice_items_invoice ON invoice_items (invoice_id);
CREATE INDEX ix_stock_movements_product ON stock_movements (product_id, created_at);
